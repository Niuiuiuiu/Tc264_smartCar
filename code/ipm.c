/* ============================================================================
 * ipm.c  ——  逆透视变换：像素 (col,row) -> 地面米制 (x,y)
 *
 * 原理：摄像头看的是地面这张平面(z=0)，平面到平面的射影映射一定是 3x3
 *       单应矩阵 H。
 *
 *       [x']     [h11 h12 h13]   [col]
 *       [y']  =  [h21 h22 h23] * [row]
 *       [w ]     [h31 h32 h33]   [  1 ]
 *
 *       x = x' / w    y = y' / w
 *
 * 本文件结构（按这个顺序读最省力）：
 *   第 1 部分  标定数据 IPM_H        —— 9 个数，标定后替换
 *   第 2 部分  可调参数              —— 4 个信任边界
 *   第 3 部分  内部缓存              —— 逆矩阵
 *   第 4 部分  ipm_init()            —— 上电调一次
 *   第 5 部分  核心变换              —— 整个模块的计算都在这里
 *   第 6 部分  调试函数              —— 可以整个删掉，不影响功能
 * ==========================================================================*/
#include "ipm.h"
#include <math.h>
#include <stdio.h>


/* ############################################################################
 * 第 1 部分：标定数据
 * ##########################################################################*/

/* ----------------------------------------------------------------------------
 * ★ 现在是占位数据，真标定后用 tools/calib_ipm.py 打印的数组整块替换 ★
 *
 * 占位来历：故意做成仿射，h31 = h32 = 0  =>  w 恒等于 1，永远不会除零
 *   row = 120 (画面最下) -> 车前方 0.10 m ；row = 30 -> 2.00 m
 *       => x = -0.02111111 * row + 2.6333333
 *   col = 0   (画面最左) -> 偏左 0.45 m  ；col = 188 -> 偏右 0.45 m
 *       => y = -0.00478723 * col + 0.45
 *
 * 效果：整幅图被压到"车前方 0.12 ~ 2.63 m、左右 ±0.45 m"的一条带子里。
 * 数学上完全不对，但单调、不翻符号、不除零，够先把整条链路跑通。
 *
 * 注意：H 是齐次矩阵，整体乘一个常数不改变映射。OpenCV 返回的 h33 一般不
 *       等于 1，所以算 w 的时候必须老老实实带 h33，不能写死 +1.0。
 * ------------------------------------------------------------------------- */
static const float IPM_H[3][3] =
{
    {  0.0f,        -0.02111111f,   2.6333333f },   /* h11  h12  h13 */
    { -0.00478723f,  0.0f,          0.45f     },   /* h21  h22  h23 */
    {  0.0f,         0.0f,          1.0f      },   /* h31  h32  h33 */
};


/* ############################################################################
 * 第 2 部分：可调参数
 * ##########################################################################*/

/* 有效范围：超出这个框的结果一律丢掉。改这里 = 改"你能信任的视野" */
#define IPM_X_MIN   ( 0.05f)        /* 太近的点不可信 */
#define IPM_X_MAX   ( 3.00f)        /* 你能看多远 */
#define IPM_Y_MIN   (-1.20f)        /* 右侧边界 */
#define IPM_Y_MAX   ( 1.20f)        /* 左侧边界 */

#define IPM_W_EPS   ( 1e-6f)        /* 分母的死亡线，不要改 */


/* ############################################################################
 * 第 3 部分：内部缓存
 * ##########################################################################*/

static float   s_inv_H[3][3];       /* H 的逆矩阵，只在 ipm_init 里算一次 */
static uint8_t s_inv_ready = 0;     /* 0 = 还没算好 / 算失败了 */


/* ############################################################################
 * 第 4 部分：ipm_init()  ——  上电调一次
 *
 * 只做一件事：把 IPM_H 求逆存进 s_inv_H，供 ipm_ground_to_uv() 反着算。
 * 求逆公式本身就是 2x2 行列式的交叉组合，不需要推导，认得结构就行。
 * 这段只在上电跑一次，所以宁可多写几行也要写得清楚。
 * ##########################################################################*/
void ipm_init(void)
{
    /* 先把 9 个数抄成和上面公式一致的名字，下面才看得懂 */
    const float h11 = IPM_H[0][0], h12 = IPM_H[0][1], h13 = IPM_H[0][2];
    const float h21 = IPM_H[1][0], h22 = IPM_H[1][1], h23 = IPM_H[1][2];
    const float h31 = IPM_H[2][0], h32 = IPM_H[2][1], h33 = IPM_H[2][2];

    float det;

    /* ---- 第 1 步：算行列式 ---- */
    det = h11 * (h22 * h33 - h23 * h32)
        - h12 * (h21 * h33 - h23 * h31)
        + h13 * (h21 * h32 - h22 * h31);

    /* ---- 第 2 步：行列式接近 0 说明 H 退化，标定数据本身有问题 ---- */
    if (fabsf(det) < 1e-12f)
    {
        s_inv_ready = 0;
        return;
    }

    /* ---- 第 3 步：逆矩阵 = 伴随矩阵 / 行列式 ----
       伴随矩阵的每个元素是一个 2x2 行列式。下面九行的下标看着有点"错位"，
       这是求逆公式本来的样子（转置伴随矩阵），不是笔误。 */
    s_inv_H[0][0] =  (h22 * h33 - h23 * h32) / det;
    s_inv_H[0][1] = -(h12 * h33 - h13 * h32) / det;
    s_inv_H[0][2] =  (h12 * h23 - h13 * h22) / det;
    s_inv_H[1][0] = -(h21 * h33 - h23 * h31) / det;
    s_inv_H[1][1] =  (h11 * h33 - h13 * h31) / det;
    s_inv_H[1][2] = -(h11 * h23 - h13 * h21) / det;
    s_inv_H[2][0] =  (h21 * h32 - h22 * h31) / det;
    s_inv_H[2][1] = -(h11 * h32 - h12 * h31) / det;
    s_inv_H[2][2] =  (h11 * h22 - h12 * h21) / det;

    s_inv_ready = 1;
}


/* ############################################################################
 * 第 5 部分：核心变换
 *
 *   ipm_uv_to_ground()      像素 -> 地面       （真正的计算）
 *   ipm_point_to_ground()    包装，吃 line_point_t
 *   ipm_ground_to_uv()      地面 -> 像素       （反着算，用逆矩阵）
 * ##########################################################################*/

/* ----------------------------------------------------------------------------
 * 核心：像素 -> 地面。整个模块的计算就是四步。
 * ------------------------------------------------------------------------- */
ipm_status_t ipm_uv_to_ground(float col, float row, ipm_ground_point_t *out)
{
    float w;
    float x;
    float y;

    if (out == 0)
    {
        return IPM_ERR_ARG;
    }

    /* ---- 第 1 步：算分母 w ----
       就是 H 的第三行点乘 (col, row, 1) */
    w = IPM_H[2][0] * col + IPM_H[2][1] * row + IPM_H[2][2];

    /* ---- 第 2 步：闸 1，地平线保护 ----
       w 越接近 0，说明这个像素越靠近地平线，x/y 会爆成天文数字或突然变号。
       这一行绝对不能省，否则远处一个噪点就能把舵机打到死。 */
    if (fabsf(w) < IPM_W_EPS)
    {
        return IPM_ERR_HORIZON;
    }

    /* ---- 第 3 步：算 x 和 y ----
       分子 = H 的第一行（算 x）/ 第二行（算 y）点乘 (col, row, 1)，
       然后都除以同一个 w */
    x = (IPM_H[0][0] * col + IPM_H[0][1] * row + IPM_H[0][2]) / w;
    y = (IPM_H[1][0] * col + IPM_H[1][1] * row + IPM_H[1][2]) / w;

    /* ---- 第 4 步：闸 2，范围保护 ----
       过了地平线 w 会变负，x/y 会"看起来很正常"地翻到负值，
       光查 |w| 挡不住，必须再查结果范围。两道闸缺一不可。 */
    if (x < IPM_X_MIN || x > IPM_X_MAX ||
        y < IPM_Y_MIN || y > IPM_Y_MAX)
    {
        return IPM_ERR_RANGE;
    }

    out->x = x;
    out->y = y;
    return IPM_OK;
}


/* ----------------------------------------------------------------------------
 * 包装：直接吃 line_detect() 的输出。
 * 唯一的作用就是把 uint16_t 转成 float —— 决不能拿整型去算，
 * 1 个像素的截断误差在 2 m 外会放大成好几厘米。
 * ------------------------------------------------------------------------- */
ipm_status_t ipm_point_to_ground(const line_point_t *in, ipm_ground_point_t *out)
{
    if (in == 0)
    {
        return IPM_ERR_ARG;
    }

    return ipm_uv_to_ground((float)in->col, (float)in->row, out);
}


/* ----------------------------------------------------------------------------
 * 反向：地面 -> 像素。结构和 ipm_uv_to_ground 完全对称，
 * 只是把 IPM_H 换成逆矩阵 s_inv_H，并且要多查一次"初始化了没"。
 * ------------------------------------------------------------------------- */
ipm_status_t ipm_ground_to_uv(float x, float y, float *col, float *row)
{
    float w;
    float c;
    float r;

    if (col == 0 || row == 0)
    {
        return IPM_ERR_ARG;
    }
    if (!s_inv_ready)
    {
        return IPM_ERR_NO_INIT;
    }

    /* ---- 第 1 步：算分母 ---- */
    w = s_inv_H[2][0] * x + s_inv_H[2][1] * y + s_inv_H[2][2];

    /* ---- 第 2 步：同样要防除零 ---- */
    if (fabsf(w) < IPM_W_EPS)
    {
        return IPM_ERR_HORIZON;
    }

    /* ---- 第 3 步：算出像素坐标 ----
       这里不做范围检查，因为输入已经是地面坐标，越界的点由调用方自己判断 */
    c = (s_inv_H[0][0] * x + s_inv_H[0][1] * y + s_inv_H[0][2]) / w;
    r = (s_inv_H[1][0] * x + s_inv_H[1][1] * y + s_inv_H[1][2]) / w;

    *col = c;
    *row = r;
    return IPM_OK;
}


/* ############################################################################
 * 第 6 部分：调试函数
 *
 *   以下两个函数不参与控制，性能无所谓。
 *   如果嫌文件长，这一整段可以删掉，不影响上面任何功能。
 * ##########################################################################*/

/* ----------------------------------------------------------------------------
 * 标定体检：把一个标定点代回 H，返回误差（米）。
 * 返回负数表示这个点算不出来（地平线外或越界）。
 * ------------------------------------------------------------------------- */
float ipm_residual_m(float col, float row, float x_ref, float y_ref)
{
    ipm_ground_point_t g;
    float dx;
    float dy;

    if (ipm_uv_to_ground(col, row, &g) != IPM_OK)
    {
        return -1.0f;
    }

    dx = g.x - x_ref;
    dy = g.y - y_ref;

    return sqrtf(dx * dx + dy * dy);
}


/* ----------------------------------------------------------------------------
 * 自检：上电调一次，看串口输出。
 *
 * 用占位 H 跑，必须看到：
 *   四个角：TL -> x≈+2.633 y≈+0.450 ；BL -> x≈+0.121 y≈+0.450
 *   全图 188x120 = 22560 点，OK = 22560，HORIZON = 0，OUT_OF_RANGE = 0
 * 只要不是 100% OK，就是代码有问题（占位数据不可能产生地平线问题）。
 *
 * 注意：这个函数内部会跑 22560 次变换，只适合上电跑一次，
 *       绝对不能放进主循环（每圈约 5 ms）。
 * ------------------------------------------------------------------------- */
void ipm_selftest(void)
{
    const int16_t  c[4]  = { 0, MT9V03X_1_W - 1, 0,               MT9V03X_1_W - 1 };
    const int16_t  r[4]  = { 0, 0,               MT9V03X_1_H - 1, MT9V03X_1_H - 1 };
    const char    *nm[4] = { "TL", "TR", "BL", "BR" };

    uint32_t n_ok  = 0;
    uint32_t n_hor = 0;
    uint32_t n_rng = 0;
    int16_t  r_first = -1;
    int16_t  r_last  = -1;
    int16_t  i;
    int16_t  rr;
    int16_t  cc;

    printf("\r\n===== IPM self test =====\r\n");

    /* ---- 第 1 段：四个角，一眼看出象限 / 符号对不对 ---- */
    for (i = 0; i < 4; i++)
    {
        ipm_ground_point_t g;

        if (ipm_uv_to_ground((float)c[i], (float)r[i], &g) == IPM_OK)
        {
            printf("  %s col=%3d row=%3d -> x=%+6d mm  y=%+6d mm\r\n",
                   nm[i], (int)c[i], (int)r[i],
                   (int)(g.x * 1000.0f), (int)(g.y * 1000.0f));
        }
        else
        {
            printf("  %s col=%3d row=%3d -> REJECTED\r\n",
                   nm[i], (int)c[i], (int)r[i]);
        }
    }

    /* ---- 第 2 段：全图统计，并记录有效行范围 ---- */
    for (rr = 0; rr < MT9V03X_1_H; rr++)
    {
        for (cc = 0; cc < MT9V03X_1_W; cc++)
        {
            ipm_ground_point_t g;

            switch (ipm_uv_to_ground((float)cc, (float)rr, &g))
            {
            case IPM_OK:
                n_ok++;
                if (r_first < 0)
                {
                    r_first = rr;
                }
                r_last = rr;
                break;

            case IPM_ERR_HORIZON:
                n_hor++;
                break;

            default:
                n_rng++;
                break;
            }
        }
    }

    printf("  image %dx%d = %u points\r\n",
           (int)MT9V03X_1_W, (int)MT9V03X_1_H,
           (unsigned)(MT9V03X_1_W * MT9V03X_1_H));
    printf("  OK=%u  HORIZON=%u  OUT_OF_RANGE=%u\r\n",
           (unsigned)n_ok, (unsigned)n_hor, (unsigned)n_rng);
    printf("  usable rows: %d .. %d\r\n", (int)r_first, (int)r_last);
    printf("=========================\r\n");
}
